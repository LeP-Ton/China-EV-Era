export const monthAt = (week: number) =>
  Math.floor(week / 13) * 3 + Math.min(2, Math.floor((week % 13) / 4));
export function gameDate(week: number): string {
  const q = Math.min(11, Math.floor(week / 13));
  return `${2026 + Math.floor(q / 4)} 年 Q${(q % 4) + 1}`;
}

